let current = 'en';
const listeners = new Set();

/** Pure language choice: stored choice → navigator language ("th…" → th) → en. */
export function detectLang({ stored = null, navLang = '' } = {}) {
  if (LANGS.includes(stored)) return stored;
  return String(navLang || '').toLowerCase().startsWith('th') ? 'th' : 'en';
}

function readStored() {
  try {
    return globalThis.localStorage ? globalThis.localStorage.getItem(STORE_KEY) : null;
  } catch {
    return null;
  }
}

function writeStored(lang) {
  try {
    globalThis.localStorage?.setItem(STORE_KEY, lang);
  } catch {
    /* storage blocked — the toggle still works for this visit */
  }
}

/** Pick the language for this visit (no persistence) and stamp <html lang>. */
export function initLang() {
  current = detectLang({ stored: readStored(), navLang: globalThis.navigator?.language });
  stampDocument();
  return current;
}

export function getLang() {
  return current;
}

/** Switch language, remember it, re-apply static strings and notify listeners. */
export function setLang(lang) {
  if (!LANGS.includes(lang) || lang === current) return current;
  current = lang;
  writeStored(lang);
  stampDocument();
  for (const fn of listeners) {
    try {
      fn(lang);
    } catch (e) {
      console.error(e);
    }
  }
  return current;
}

/** fn(lang) after every switch; returns an unsubscribe function. */
export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Translate `key` with {placeholders}; falls back to English, then to the key itself. */
export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.en;
  let s = table[key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) return key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined || vars[name] === null ? m : String(vars[name])));
}

/** Does `key` exist (in English, the reference table)? errText() uses it to tell a known code from an unknown one. */
export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(STRINGS.en, key);
}

/**
 * Count-aware t(): `${key}_one` when `count` is 1 and the CURRENT language defines it (Thai has no
 * plural, so its _one strings equal the others). `{n}` defaults to `count`; pass vars.n to format it.
 */
export function tn(key, count, vars = {}) {
  const table = STRINGS[current] || STRINGS.en;
  const one = Number(count) === 1 && table[`${key}_one`] !== undefined;
  return t(one ? `${key}_one` : key, { n: count, ...vars });
}

/** Suffixes for format.ago() in the current language. */
export function agoUnits() {
  return { s: t('ago.s'), m: t('ago.m'), h: t('ago.h'), d: t('ago.d') };
}

/**
 * Fill static markup:
 *   <span data-i18n="shelf.title">…</span>                       → textContent
 *   <input data-i18n-attr="placeholder:token.placeholder;aria-label:token.label">
 */
export function applyI18n(root = globalThis.document) {
  if (!root?.querySelectorAll) return;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    // data-i18n-bare: drop a leading emoji/symbol ("🌱 Seeds" → "Seeds") where an SVG icon already says it
    el.textContent = 'i18nBare' in el.dataset ? bareText(t(el.dataset.i18n)) : t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map((x) => x && x.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }
}

/** "🌱 Seeds" → "Seeds", "⏩ +1h · SIM only" → "+1h · SIM only" (letters, digits and signs are kept). */
export function bareText(s) {
  return String(s ?? '').replace(/^[^\p{L}\p{N}+−-]+/u, '');
}

function stampDocument() {
  const html = globalThis.document?.documentElement;
  if (html) html.lang = current;
}
